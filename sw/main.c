#include "address_map_arm.h"
#include <stdio.h>
#include <stdlib.h>

// Set the base addresses of the registers for the Booth multiplier
#define REG0 0xFF200000 // multiplicand data_a
#define REG1 0xFF200004 // multiplier data_b
#define REG2 0xFF200008 // stores the result of multiplication 
#define REG3 0xFF20000C // start/busy/ack status

void set_A9_IRQ_stack(void);
void config_GIC(void);
void enable_A9_interrupts(void);

volatile int MULTIPLICATION_FINISHED = 0;

int main(void)
{
  //Reading the base address of the registers for the Booth multiplier, and storing them in pointers.
  volatile int *reg0 = (int *)REG0; 
  volatile int *reg1 = (int *)REG1; 
  volatile int *reg2 = (int *)REG2; 
  volatile int *reg3 = (int *)REG3; 
  int result;

  set_A9_IRQ_stack();      // initialize the stack pointer for IRQ mode
  config_GIC();            // configure the general interrupt controller
  enable_A9_interrupts(); // enable interrupts

  printf("\n Radix-4 Booth Multiplier \n");

  while (1)
  {
    // Check if the multiplier is busy before starting a new multiplication operation. 
    printf("\n 1: Checking busy bit\n");
    int busy = (*reg3 >> 1) & 0x1;
    printf("Busy: %d\n", busy);

    if (busy == 1)
    {
      //Wait for the busy bit to disable before
      //the next operation
      printf("Multiplier is busy\n");
      continue;
    }

    // If IRQ is generated by the booth multiplier, we need to clear the interrupt by toggling the ack bit 
    printf("\n 2: Clear IRQ\n");
    int val = *reg3;
    val |= (1 << 2); // ack = 1
    *reg3 = val; // Write to volatile register
    val = *reg3;
    val &= ~(1 << 2); // ack = 0
    *reg3 = val; // Write to volatile register

    //  Read user input for multiplicand and multiplier, and store them in the corresponding registers
    int16_t multiplicand_input, multiplier_input; //16 bit input for the user
    printf("Enter data_a (16-bit): ");
    scanf("%hd", &multiplicand_input);
    
    printf("Enter data_b (16-bit): ");
    scanf("%hd", &multiplier_input);

    // Storing the user input in the corresponding registers
    *reg0 = multiplicand_input; //Write data_a to slv_reg0
    *reg1 = multiplier_input; //Write data_b to slv_reg1
    printf("Wrote %d (%d) to REG0, %d (%d) to REG1, \n", multiplicand_input, *reg0, multiplier_input, *reg1);


    // Set the start bit to 1 to start the multiplication operation
    val = *reg3; //Read status of start/busy/ack from slv_reg3
    val |= (1 << 0); // set start = 1
    *reg3 = val; //Write to reg3
    printf("Started multiplication\n");
    
    // Wait for the multiplication to finish by monitoring the MULTIPLICATION_FINISHED flag
    printf("Waiting for interrupt...\n");
    while (!MULTIPLICATION_FINISHED)
    {
    }
    MULTIPLICATION_FINISHED = 0; //Clear flag
    
    printf("Interrupt received!\n");
    
    // Clear the start bit to 0 after acknowledging the completion of the multiplication operation
    val = *reg3;
    val &= ~(1 << 0); // start = 0
    *reg3 = val;
    
    // Read the result from the corresponding register and print it
    printf("Result: %d\n", *reg2);

  }

  return 0;
}
